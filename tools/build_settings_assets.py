#!/usr/bin/env python3
"""Embed the offline settings page and a reproducible 512px Media tile icon."""
import pathlib
import struct
import sys
import zlib


def icon():
    size = 512
    pixels = bytearray(size * size * 3)
    def rect(x, y, w, h, rgb):
        for row in range(y, y+h):
            pixels[(row*size+x)*3:(row*size+x+w)*3] = bytes(rgb)*w
    for y in range(size):
        rect(0, y, size, 1, (18+y//32, 28+y//24, 48+y//12))
    segments = ((20,0,80,20),(100,20,20,80),(100,120,20,80),
                (20,200,80,20),(0,120,20,80),(0,20,20,80),(20,100,80,20))
    for x, on in ((110, (0,2,3,4,5,6)), (282, (0,1,2,3,4,5))):
        for i in on:
            a,b,w,h = segments[i]
            rect(x+a, 108+b, w, h, (204,174,255))
    glyphs = ('111/100/110/100/100', '110/101/110/100/100', '111/100/111/001/111')
    for i, glyph in enumerate(glyphs):
        for y, row in enumerate(glyph.split('/')):
            for x, bit in enumerate(row):
                if bit == '1': rect(174+i*60+x*14, 376+y*14, 12, 12, (238,245,255))
    raw = b''.join(b'\0'+pixels[y*size*3:(y+1)*size*3] for y in range(size))
    def chunk(kind, data):
        return struct.pack('>I', len(data))+kind+data+struct.pack('>I', zlib.crc32(kind+data))
    return (b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>2I5B',size,size,8,2,0,0,0))+
            chunk(b'IDAT',zlib.compress(raw,9))+chunk(b'IEND',b''))


if __name__ == '__main__':
    root, target = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    assets = {'commonfps_settings_html': (root/'assets/settings/index.html').read_bytes(),
              'commonfps_settings_param': (root/'assets/settings/param.json').read_bytes(),
              'commonfps_settings_icon': icon()}
    target.parent.mkdir(parents=True, exist_ok=True)
    with target.open('w') as out:
        out.write('// Generated by build_settings_assets.py\n#include <cstddef>\nextern "C" {\n')
        for name, data in assets.items():
            out.write('extern const unsigned char '+name+'[] = {\n')
            for pos in range(0,len(data),24):
                out.write(','.join(str(b) for b in data[pos:pos+24])+',\n')
            out.write('};\nextern const std::size_t '+name+'_size = '+str(len(data))+';\n')
        out.write('}\n')
